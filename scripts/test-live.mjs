// Opt-in Windows/Google acceptance. Requires an already saved user-owned key.
// No credentials, provider payloads or transcript content are written to artifacts.
import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { quitTestedApp } from './quit-tested-app.mjs';

const humanMatrix = process.argv.includes('--human-matrix');
const human = humanMatrix || process.argv.includes('--human');
const requestedHumanLanguage = process.argv
  .find((argument) => argument.startsWith('--human-language='))
  ?.split('=')[1];
const prompts = [
  { language: 'English', sentence: 'The blue notebook is beside the window.' },
  {
    language: 'Hindi',
    sentence: 'मेरी नीली किताब खिड़की के पास है।',
    spoken: 'Meri neeli kitaab khidki ke paas hai.',
    roman: [
      'Meri neeli kitaab khidki ke paas hai.',
      'Meri neeli kitab khidki ke paas hai.',
      'Meri nili kitab khidki ke paas hai.',
    ],
  },
  { language: 'Hinglish', sentence: 'Please kal subah meeting ka reminder set kar dena.' },
].filter(
  (prompt) =>
    !requestedHumanLanguage ||
    prompt.language.toLowerCase() === requestedHumanLanguage.toLowerCase(),
);
assert.ok(prompts.length > 0, 'Choose English, Hindi or Hinglish for --human-language.');
const normalizePrompt = (text) =>
  text
    .normalize('NFC')
    .replace(/[\p{P}\p{Z}\s]/gu, '')
    .toLowerCase();
const operator = humanMatrix ? createInterface({ input: process.stdin }) : undefined;
const hardware = human || process.argv.includes('--hardware');
const development = process.argv.includes('--development');
const caretPlacement = process.argv.includes('--caret');
const repeats = humanMatrix ? prompts.length : process.argv.includes('--repeat') ? 2 : 1;
const insertionMethod = process.argv.includes('--paste') ? 'paste' : 'unicode';
const imageClipboard = process.argv.includes('--image-clipboard');
const clipboardKind = imageClipboard
  ? 'image'
  : process.argv.includes('--text-clipboard')
    ? 'text'
    : undefined;
const executableArgument = process.argv.find((argument) => argument.startsWith('--executable='));
const profileArgument = process.argv.find((argument) => argument.startsWith('--profile='));
const warm = process.argv.includes('--warm');
const wav = resolve('.tools/live-speech.wav');
const bytes = await readFile(wav);
// Generated by System.Speech as mono PCM16, 16 kHz.
const seconds = Math.ceil(bytes.length / 32000) + 2;
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
delete env.ELECTRON_RENDERER_URL;
const child = spawn(
  resolve(
    development
      ? 'node_modules/electron/dist/electron.exe'
      : executableArgument?.slice('--executable='.length) || '.tools/installed/Seyvo.exe',
  ),
  [
    ...(development ? [process.cwd()] : []),
    ...(profileArgument
      ? [`--user-data-dir=${resolve(profileArgument.slice('--profile='.length))}`]
      : []),
    '--remote-debugging-port=0',
    ...(!hardware
      ? ['--use-fake-device-for-media-stream', `--use-file-for-fake-audio-capture=${wav}%noloop`]
      : []),
  ],
  { env, windowsHide: true, stdio: ['ignore', 'ignore', 'pipe'] },
);
const host = spawn(resolve('artifacts/native/TestHost.exe'), [], {
  windowsHide: true,
  stdio: ['pipe', 'pipe', 'ignore'],
});
const lines = createInterface({ input: host.stdout });
const queued = [],
  waiting = [];
lines.on('line', (line) => {
  const done = waiting.shift();
  if (done) done(line);
  else queued.push(line);
});
function next() {
  if (queued.length) return Promise.resolve(queued.shift());
  return new Promise((done, fail) => {
    const timer = setTimeout(() => fail(new Error('Test host response timed out')), 10000);
    waiting.push((line) => {
      clearTimeout(timer);
      done(line);
    });
  });
}
async function command(value) {
  host.stdin.write(value + '\n');
  return next();
}
let browser, page, settings;
let ownsSession = false;
async function waitPhase(phases) {
  const deadline = Date.now() + 30000;
  let observed;
  while (Date.now() < deadline) {
    const status = await page.evaluate(() => window.seyvo.status());
    observed = { phase: status.phase, microphoneActive: status.microphoneActive };
    if (phases.includes(status.phase)) return status;
    await new Promise((done) => setTimeout(done, 100));
  }
  throw new Error(
    `Timed out waiting for dictation state (${observed?.phase}, microphone ${observed?.microphoneActive ? 'on' : 'off'}).`,
  );
}
const report = {
  packaged: !development,
  audioSource: human
    ? 'Live spoken test through Windows physical microphone'
    : hardware
      ? 'Windows physical microphone; generated sentence played through speakers'
      : 'Generated speech WAV through Chromium capture and the real recorder worklet',
  googleMocked: false,
  insertionMethod,
};
try {
  const endpoint = await new Promise((done, fail) => {
    const timer = setTimeout(() => fail(new Error('Installed app did not start')), 20000);
    child.stderr.on('data', (chunk) => {
      const match = chunk.toString().match(/DevTools listening on (ws:\/\/[^\s]+)/);
      if (match) {
        clearTimeout(timer);
        done(match[1]);
      }
    });
    child.on('error', () => fail(new Error('Installed app launch failed')));
  });
  browser = await chromium.connectOverCDP(endpoint);
  const context = browser.contexts()[0];
  page =
    context.pages().find((p) => p.url().includes('index.html') && !p.url().includes('#')) ??
    (await context.waitForEvent('page'));
  await page.waitForFunction(() => Boolean(window.seyvo));
  const initial = await page.evaluate(() => window.seyvo.status());
  report.version = initial.version;
  report.buildHash = initial.buildHash;
  assert.equal(initial.hasKey, true, 'Save a user-owned key in the app before this opt-in test.');
  assert.equal(initial.microphoneActive, false);
  assert.ok(!initial.recovery, 'Resolve existing recovery before running acceptance.');
  assert.equal(
    initial.settings.historyEnabled,
    false,
    'Turn history off before this synthetic test.',
  );
  ownsSession = true;
  settings = initial.settings;
  report.languageHints = initial.settings.languages;
  report.transcriptionMode = initial.settings.mode;
  const connected = await page.evaluate(() => window.seyvo.testKey());
  assert.equal(connected.ok, true, connected.error);
  report.googleSetup = 'passed';
  const configured = await page.evaluate(
    ({ caretPlacement, insertionMethod }) =>
      window.seyvo.updateSettings({
        shortcut: 'F8',
        insertion: insertionMethod,
        paused: false,
        deviceId: 'default',
        ...(caretPlacement ? { overlayPosition: 'caret', showOverlay: true, captions: false } : {}),
      }),
    { caretPlacement, insertionMethod },
  );
  assert.equal(configured.ok, true, configured.error);
  assert.equal(await next(), 'ready');
  if (warm) {
    const deadline = Date.now() + 20000;
    while ((await page.evaluate(() => window.seyvo.status())).connectionState !== 'ready') {
      assert.ok(Date.now() < deadline, 'Google standby did not become ready.');
      await new Promise((done) => setTimeout(done, 100));
    }
    await new Promise((done) => setTimeout(done, 10000));
    const idle = await page.evaluate(() => window.seyvo.status());
    assert.equal(idle.connectionState, 'ready');
    assert.equal(idle.microphoneActive, false);
    report.idleGoogleReadySeconds = 10;
    const recorder = context.pages().find((candidate) => candidate.url().endsWith('recorder.html'));
    assert.ok(recorder, 'Recorder page should preload without opening a microphone.');
    await recorder.evaluate(() => {
      const tracks = [];
      globalThis.acceptanceTracks = tracks;
      const original = navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices);
      navigator.mediaDevices.getUserMedia = async (constraints) => {
        const stream = await original(constraints);
        tracks.push(...stream.getTracks());
        return stream;
      };
    });
    await page.evaluate(() => {
      globalThis.acceptancePhases = [];
      window.seyvo.subscribe((status) =>
        globalThis.acceptancePhases.push({
          phase: status.phase,
          microphoneActive: status.microphoneActive,
          waitingForGoogle: status.message === 'Connecting to Google…',
          time: Date.now(),
        }),
      );
    });
  }
  if (clipboardKind)
    assert.equal(await command(`clipboard-${clipboardKind}-observe`), `${clipboardKind}-observed`);
  let cumulative = '';
  report.sessions = [];
  for (let cycle = 0; cycle < repeats; cycle++) {
    if (warm) {
      const deadline = Date.now() + 65000;
      while ((await page.evaluate(() => window.seyvo.status())).connectionState !== 'ready') {
        assert.ok(
          Date.now() < deadline,
          'Google standby did not recover within its request budget.',
        );
        await new Promise((done) => setTimeout(done, 100));
      }
      await page.evaluate(() => {
        globalThis.acceptancePhases = [];
      });
    }
    if (humanMatrix) {
      console.log(
        `READY ${prompts[cycle].language}: ${prompts[cycle].spoken ?? prompts[cycle].sentence}`,
      );
      console.log(
        'Press Enter to begin this 15-second recording. No audio is captured while waiting.',
      );
      await new Promise((done, fail) => {
        const timer = setTimeout(() => {
          operator.removeListener('line', ready);
          fail(new Error('Operator readiness timed out.'));
        }, 180000);
        function ready() {
          clearTimeout(timer);
          done();
        }
        operator.once('line', ready);
      });
    }
    assert.equal(
      await command('focus'),
      'focused',
      'No input is sent outside the owned test window.',
    );
    const activatedAt = Date.now();
    assert.equal(await command('shortcut'), 'shortcut-sent');
    const recording = await waitPhase(['listening', 'error']);
    assert.equal(recording.phase, 'listening', recording.message);
    assert.equal(recording.targetApp.toLowerCase(), 'testhost.exe');
    assert.equal(recording.microphoneActive, true);
    if (caretPlacement) {
      const overlay = context.pages().find((candidate) => candidate.url().includes('#overlay'));
      assert.ok(overlay, 'The installed caret bubble must be present.');
      await overlay.waitForLoadState('load');
      assert.equal(recording.settings.overlayPosition, 'caret');
      // This generated fixture has captions disabled. Never capture a human transcript.
      if (!hardware) {
        await mkdir('artifacts/live', { recursive: true });
        await overlay.screenshot({ path: 'artifacts/live/installed-caret-bubble.png' });
      }
      report.overlayPlacement = 'caret mode enabled in installed live session';
    }
    if (human) {
      console.log('Listening for the spoken acceptance sentence for 15 seconds.');
      await new Promise((done) => setTimeout(done, 15000));
    } else if (hardware) {
      // A fixed, known synthetic sentence. Shell text never contains credentials or dictation.
      const player = spawn(
        'powershell.exe',
        [
          '-NoProfile',
          '-ExecutionPolicy',
          'Bypass',
          '-File',
          resolve('scripts/live-speech.ps1'),
          '-Play',
        ],
        { windowsHide: true, stdio: 'ignore' },
      );
      await new Promise((done) => player.once('exit', done));
    } else await new Promise((done) => setTimeout(done, seconds * 1000));
    // The interactive workstation may have been used during the audio interval.
    // Explicitly select only this runner's owned field before sending Stop.
    // Production capture, caret identity and refusal checks remain unchanged.
    assert.equal(await command('focus'), 'focused', 'Could not reselect the owned test field.');
    if (humanMatrix) {
      const stopped = await page.evaluate(() => window.seyvo.action('stop'));
      assert.equal(stopped.ok, true, stopped.error);
    } else {
      assert.equal(
        await command('shortcut'),
        'shortcut-sent',
        'Stop requires the original test window to remain foreground.',
      );
    }
    const result = await waitPhase(['recovery', 'error', 'idle']);
    assert.equal(result.microphoneActive, false);
    assert.equal(result.phase, 'idle', result.message);
    cumulative += result.recovery;
    // SendInput queues Windows messages; give the target a chance to consume them.
    let inserted = '';
    for (let attempt = 0; attempt < 20; attempt++) {
      inserted = Buffer.from(await command('text'), 'base64').toString();
      if (inserted === cumulative) break;
      await new Promise((done) => setTimeout(done, 100));
    }
    report.textChecks = {
      recognizedCharacters: result.recovery.length,
      insertedCharacters: inserted.length,
      matchesFinal: inserted === cumulative,
      ...(!human
        ? {
            expectedWords:
              /lighthouse/i.test(result.recovery) && /blue river/i.test(result.recovery),
          }
        : {}),
    };
    assert.ok(
      human
        ? result.recovery.trim().length > 0
        : /lighthouse/i.test(result.recovery) && /blue river/i.test(result.recovery),
      `Expected test sentence was not inserted. Status: ${result.message}`,
    );
    assert.ok(
      inserted === cumulative,
      'The target did not receive exactly the consecutive finalized text.',
    );
    report.sessions.push({
      cycle: cycle + 1,
      ...report.textChecks,
      phase: result.phase,
      ...(humanMatrix
        ? {
            language: prompts[cycle].language,
            // Punctuation/case differences are ignored, never the actual text.
            matchesSpokenPrompt: [prompts[cycle].sentence, ...(prompts[cycle].roman ?? [])].some(
              (expected) => normalizePrompt(result.recovery) === normalizePrompt(expected),
            ),
            hasDevanagari: /[\u0900-\u097f]/u.test(result.recovery),
            hasLatin: /[a-z]/i.test(result.recovery),
          }
        : {}),
    });
    if (warm) {
      const phases = await page.evaluate(() => globalThis.acceptancePhases);
      assert.equal(
        phases.some((state) => state.waitingForGoogle),
        false,
        'Warm activation waited for Google setup.',
      );
      const listening = phases.find(
        (state) => state.phase === 'listening' && state.microphoneActive,
      );
      assert.ok(listening);
      report.sessions.at(-1).shortcutToListeningMs = listening.time - activatedAt;
      report.sessions.at(-1).waitedForGoogleSetup = false;
      const recorder = context
        .pages()
        .find((candidate) => candidate.url().endsWith('recorder.html'));
      assert.ok(recorder);
      assert.equal(
        await recorder.evaluate(
          () =>
            globalThis.acceptanceTracks.length > 0 &&
            globalThis.acceptanceTracks.every((track) => track.readyState === 'ended'),
        ),
        true,
      );
      report.sessions.at(-1).allCapturedTracksEnded = true;
    }
    if (humanMatrix) console.log(JSON.stringify(report.sessions.at(-1)));
    if (clipboardKind) {
      assert.equal(
        await command(`clipboard-${clipboardKind}-unchanged`),
        `${clipboardKind}-unchanged`,
      );
      report.clipboardPreserved = clipboardKind;
    }
  }
  report.globalShortcut = humanMatrix
    ? 'started using real Windows F8; stopped through the normal main-process Stop action'
    : 'started and stopped using real Windows key events';
  report.insertion = 'recognized test sentence reached original native text field';
  report.microphoneAfterStop = 'off';
  report.transcriptLogged = false;
  report.pipelineResult = 'passed';
  report.result =
    humanMatrix && report.sessions.some((session) => !session.matchesSpokenPrompt)
      ? 'partial: insertion passed; spoken prompt needs review'
      : 'passed';
} catch (error) {
  report.result = 'failed';
  report.error = error.message;
  process.exitCode = 1;
} finally {
  if (page) {
    if (ownsSession) {
      await page.evaluate(() => window.seyvo.action('cancel')).catch(() => {});
      await page.evaluate(() => window.seyvo.action('dismiss')).catch(() => {});
    }
    if (settings) {
      const { shortcut, insertion, paused, deviceId, overlayPosition, showOverlay, captions } =
        settings;
      await page
        .evaluate((patch) => window.seyvo.updateSettings(patch), {
          shortcut,
          insertion,
          paused,
          deviceId,
          overlayPosition,
          showOverlay,
          captions,
        })
        .catch(() => {});
    }
    try {
      await quitTestedApp(page, child, browser);
      report.cleanExit = true;
    } catch {
      report.result = 'failed';
      report.error = 'The tested app did not exit cleanly.';
      report.exitCode = child.exitCode;
      report.exitSignal = child.signalCode;
      process.exitCode = 1;
    }
  }
  await browser?.close().catch(() => {});
  child.kill();
  host.kill();
  lines.close();
  operator?.close();
  await mkdir('artifacts/live', { recursive: true });
  await writeFile(
    `artifacts/live/${human ? 'spoken-microphone' + (requestedHumanLanguage ? '-' + prompts[0].language.toLowerCase() : '') : hardware ? 'microphone' : 'recorded-speech'}.json`,
    JSON.stringify(report, null, 2),
  );
  console.log(JSON.stringify(report, null, 2));
}
